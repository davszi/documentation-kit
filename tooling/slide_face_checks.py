"""Slide faces in the built pages: where each face sits, and numbers only on a face.

The [slide-face rule](../rules/writing/pages.md#slide-faces) lets a chapter
open with one face and lets a face show no fact that its chapter lacks. Lint
reads the generated pages under `.build/docs/html/` and reports:

- an error for a chapter with more than one face, a face that does not open
  its chapter, and a face outside every chapter;
- a warning, which fails `lint --strict`, for each chapter whose face shows a
  number that the chapter does not show outside the face;
- a note for each number a project accepted on one face on purpose, and a
  warning for an acceptance mark that is unusable or no longer needed.

Chapters are the reader's chapter sections, or the outermost `section.card`
elements on a page without the reader, as in the `slides` command. A face opens
its chapter when nothing readable comes before it inside the chapter: every
element that starts before the face contains it or was generated by the
reader (the heading of an introduction chapter), and no text but white space
precedes it.

The number check needs no list from the project. It compares what the face
shows with what the chapter shows, in the same built page:

- Face side: the text a reader sees on the face, SVG text and `noscript`
  included. Not read: `script`, `style`, `template`, SVG `title` and `desc`,
  elements marked `hidden`, attributes (alt text and accessible names are not
  shown on the face) and the deck's `slide-number`.
- Chapter side: every text of the chapter outside its face, code, tables,
  hidden panels, `noscript` fallbacks and SVG text included, plus the `alt`,
  `aria-label` and `title` attributes, which state text to a reader. Scripts,
  styles and templates are not read.

Text is split at every element boundary, inline ones included, because a label
styled as a block is often an inline element: "Mean error<span>3,975</span>"
reads as 3975, not as part of a name. A number split across elements is read
in parts, on both sides alike.

Numbers are compared after normalisation. These are treated as equal:

- digit groups with or without a thousands separator: a comma, a thin space
  (U+2009), a narrow no-break space (U+202F) or a no-break space (U+00A0)
  before exactly three digits, so 1,036 and 1036 are one number. A separator
  followed by anything but a group of three digits ends the number, and the
  digits after it are not read: "0,5" reads as 0, and "error3,975" as nothing,
  because the 3 belongs to a name and ",975" is no number on its own;
- the Unicode minus (U+2212) and the hyphen-minus as a sign; a sign counts only
  when no letter, digit or point comes directly before it, so "1-2" is 1 and 2;
- trailing zeros after the decimal point: 0.500, 0.50 and 0.5; 3.0 and 3;
  a leading point is a zero: .5 and 0.5; negative zero is zero;
- a percent sign directly after the number or after white space: 12%, 12 % and
  12<small>%</small> are one number, which differs from 12 without a percent
  sign;
- an ISO date (2026-11-15) is one number, compared whole.

Not counted, because it is not a fact but a label or decoration:

- an integer written with a leading zero, such as 01 or 02: the numbering of
  points and markers;
- a number after Figure, Fig., Table, Chapter, Section or Appendix in the same
  run of text: it names a part of the page, which the chapter may number
  differently or not in text.
  "Step" is not among them: "step 50 of 200" on a face is a quantity;
- a version or address such as 1.2.3: the parts are not quantities;
- digits joined to a letter, underscore or point before them, such as H100,
  v4 or the 5 in file.5: they are part of a name.

A project accepts one number on one face on purpose by wrapping exactly that
number in an element with `data-face-only="<reason>"` inside the face. Lint
prints the acceptance as a note. A mark holding no number or several, a mark
without a reason, and a mark whose number the chapter now shows are warnings,
so that a stale acceptance does not outlive its reason.

Not checked: words, claims and units other than the percent sign; numbers in
pictures (raster images and SVG files the face or chapter loads by URL);
numbers that a script writes into the page when it runs; and rounding, so 0.47
on a face and 0.4712 in the chapter are a finding to settle by hand.
"""
from __future__ import annotations

from html.parser import HTMLParser
from pathlib import Path
import re

from chapter_layout import Structure
from slides import chapters_with_faces
from topic_structure import page_sources

ACCEPT = "data-face-only"
LISTED = 12  # numbers named per finding before the rest is counted

# Labels and names blanked before numbers are read; each covers text that is not a stated quantity.
_LABELS = (
    re.compile(r"\b(?:Figure|Fig\.|Table|Chapter|Section|Appendix)[ \t\u00a0]*\d+\b", re.I),
    re.compile(r"(?<![\w.])\d+(?:\.\d+){2,}(?![\w])"),  # versions, addresses
)
_DATE = re.compile(r"(?<![\w.])\d{4}-\d{2}-\d{2}(?![\w])")
_SPACE = "\u2009\u202f\u00a0"
_NUMBER = re.compile(
    r"(?<![\w.])(?<!\d[," + _SPACE + r"])(?:(?P<int>\d{1,3}(?:[," + _SPACE + r"]\d{3})+(?!\d)|\d+)(?P<frac>\.\d+)?|(?P<lead>\.\d+))"
    r"(?P<pct>\s*%)?")
_SKIP = {"script", "style", "template"}
_STATED_ATTRS = ("alt", "aria-label", "title")


def numbers(text: str) -> list[str]:
    """Normalised numbers in the order the text shows them, labels and names left out."""
    found = []
    for pattern in _LABELS:
        text = pattern.sub(lambda match: " " * len(match.group(0)), text)
    text = text.replace("−", "-")

    def take_date(match):
        found.append((match.start(), match.group(0)))
        return " " * len(match.group(0))
    text = _DATE.sub(take_date, text)
    for match in _NUMBER.finditer(text):
        integer = match["int"]
        if integer is not None and len(integer) > 1 and integer.startswith("0"):
            continue  # 01, 02: numbering, not a quantity
        integer = re.sub("[," + _SPACE + "]", "", integer) if integer is not None else "0"
        fraction = (match["frac"] or match["lead"] or "").rstrip("0").rstrip(".")
        value = integer + fraction
        start = match.start()
        negative = (start > 0 and text[start - 1] == "-"
                    and (start < 2 or not re.match(r"[\w.]", text[start - 2])))
        if negative and value.strip("0.") != "":
            value = "-" + value
        if match["pct"]:
            value += "%"
        found.append((start, value))
    return [value for _, value in sorted(found)]


class _Text(HTMLParser):
    """Text runs of a piece of markup, split at every element boundary."""

    def __init__(self, *, face: bool):
        super().__init__(convert_charrefs=True)
        self.face, self.parts, self.skip, self.stack = face, [], 0, []
        self.accepted: list[tuple[str, list[str]]] = []  # (reason, numbers) per acceptance mark
        self._mark: list | None = None
        self._mark_depth = 0

    def _skipped(self, tag: str, attrs: dict) -> bool:
        if tag in _SKIP:
            return True
        if self.face:
            classes = (attrs.get("class") or "").split()
            return tag in {"title", "desc"} or "hidden" in attrs or "slide-number" in classes
        return False

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag in Structure.VOID:
            self._void(tag, attrs)
            return
        self.stack.append(tag)
        if self.skip:
            self.skip += 1
            return
        if self._skipped(tag, attrs):
            self.skip = 1
            return
        self.parts.append("\n")
        if not self.face:
            self._attributes(attrs)
        if self._mark is not None:
            self._mark_depth += 1
        elif self.face and ACCEPT in attrs:
            self._mark, self._mark_depth = [attrs.get(ACCEPT) or "", []], 1

    def handle_startendtag(self, tag, attrs):
        self._void(tag, dict(attrs)) if tag in Structure.VOID else (self.handle_starttag(tag, attrs), self.handle_endtag(tag))

    def _void(self, tag, attrs):
        if self.skip:
            return
        self.parts.append("\n")
        if not self.face:
            self._attributes(attrs)

    def _attributes(self, attrs):
        for name in _STATED_ATTRS:
            if attrs.get(name):
                self.parts.append("\n" + attrs[name] + "\n")

    def handle_endtag(self, tag):
        if tag in Structure.VOID or not self.stack:
            return
        self.stack.pop()
        if self.skip:
            self.skip -= 1
            return
        self.parts.append("\n")
        if self._mark is not None:
            self._mark_depth -= 1
            if self._mark_depth == 0:
                reason, runs = self._mark
                self.accepted.append((reason.strip(), numbers("".join(runs))))
                self._mark = None

    def handle_data(self, data):
        if self.skip:
            return
        if self._mark is not None:
            self._mark[1].append(data)
        else:
            self.parts.append(data)

    def text(self) -> str:
        return "".join(self.parts)


def face_text(markup: str) -> tuple[str, list[tuple[str, list[str]]]]:
    """The text a reader sees on a face, without accepted numbers, and the acceptance marks."""
    parser = _Text(face=True)
    parser.feed(markup)
    parser.close()
    return parser.text(), parser.accepted


def chapter_text(markup: str) -> str:
    parser = _Text(face=False)
    parser.feed(markup)
    parser.close()
    return parser.text()


def _opens(page: str, chapter, face) -> bool:
    """Nothing readable comes before the face inside its chapter."""
    generated = [node for node in chapter.descendants() if "data-reader-generated" in node.attrs]
    before = [node for node in chapter.descendants()
              if node is not chapter and node.start < face.start and not node.start <= face.start < node.end
              and not any(g.start <= node.start < g.end for g in generated)]
    if before:
        return False
    text = page[chapter.opening_end:face.start]
    for node in reversed(generated):
        if node.end <= face.start:
            a, b = node.start - chapter.opening_end, node.end - chapter.opening_end
            text = text[:a] + text[b:]
    return not re.sub(r"<!--[\s\S]*?-->|<[^>]*>", "", text).strip()


def _listed(values: list[str]) -> str:
    more = f" and {len(values) - LISTED} more" if len(values) > LISTED else ""
    return ", ".join(values[:LISTED]) + more


def check_page(page: str, name: str) -> tuple[list[str], list[str], list[str], dict]:
    """(errors, warnings, notes, counts) for one built page; `name` labels the page in messages."""
    errors: list[str] = []
    warnings: list[str] = []
    notes: list[str] = []
    counts = {"faces": 0, "findings": 0, "accepted": 0}
    if "data-slide-face" not in page:
        return errors, warnings, notes, counts
    try:
        found, outside = chapters_with_faces(page)
    except ValueError as problem:
        return [f"{name}: slide faces not checked; the built page does not parse: {problem}"], [], [], counts
    counts["faces"] = len(outside) + sum(len(faces) for _, faces in found)
    for _ in outside:
        errors.append(f"{name}: a slide face outside every chapter; a face opens a chapter")
    for chapter, faces in found:
        where = f'{name}, chapter "{chapter.attrs.get("id") or "(no id)"}"'
        if len(faces) > 1:
            errors.append(f"{where}: {len(faces)} slide faces; a chapter opens with at most one")
        if not _opens(page, chapter, faces[0]):
            errors.append(f"{where}: the slide face does not open the chapter; write it at the chapter's start")
        rest = page[chapter.opening_end:chapter.closing_start]
        for face in reversed(faces):
            a, b = face.start - chapter.opening_end, face.end - chapter.opening_end
            rest = rest[:a] + " " + rest[b:]
        stated = set(numbers(chapter_text(rest)))
        for index, face in enumerate(faces):
            label = where if len(faces) == 1 else f"{where}, face {index + 1}"
            shown, accepted = face_text(page[face.start:face.end])
            only = [value for value in dict.fromkeys(numbers(shown)) if value not in stated]
            if only:
                counts["findings"] += len(only)
                warnings.append(f"{label}: numbers shown only on the slide face: {_listed(only)}. "
                                f"State each in the chapter, or mark one shown on purpose with "
                                f'{ACCEPT}="<reason>"')
            for reason, values in accepted:
                if len(values) != 1:
                    warnings.append(f"{label}: a {ACCEPT} mark must hold exactly one number; "
                                    f"it holds {len(values)}" + (f" ({_listed(values)})" if values else ""))
                elif not reason:
                    warnings.append(f"{label}: the {ACCEPT} mark on {values[0]} gives no reason")
                elif values[0] in stated:
                    warnings.append(f"{label}: the {ACCEPT} mark on {values[0]} is no longer needed; "
                                    f"the chapter shows it")
                else:
                    counts["accepted"] += 1
                    notes.append(f"{label}: {values[0]} is shown only on the slide face, accepted: {reason}")
    return errors, warnings, notes, counts


def check(root: Path) -> tuple[list[str], list[str], list[str], dict]:
    """(errors, warnings, notes, counts) over every built page of the project."""
    root = Path(root)
    built = root / ".build/docs/html"
    names = page_sources(root)
    errors: list[str] = []
    warnings: list[str] = []
    notes: list[str] = []
    totals = {"pages": 0, "faces": 0, "findings": 0, "accepted": 0}
    for path in sorted(built.glob("*.html")) if built.is_dir() else []:
        source = names.get(path.name)
        name = f"{source} ({path.name})" if source else f".build/docs/html/{path.name}"
        found = check_page(path.read_text(errors="replace"), name)
        errors += found[0]
        warnings += found[1]
        notes += found[2]
        if found[3]["faces"]:
            totals["pages"] += 1
        for key in ("faces", "findings", "accepted"):
            totals[key] += found[3][key]
    return errors, warnings, notes, totals
